let accum g l invN yr yi r =
  loop l (fun q r0 ->
    let d0 = toint (mul0 (get yr q) invN) in
    let d1 = toint (mul0 (get yi q) invN) in
    set r0 q
      (add (add (get r0 q) (lsl0 d0 (mul (Uint63.of_int (12)) g)))
        (lsl0 d1 (add (mul (Uint63.of_int (12)) g) (Uint63.of_int (6))))))
