#!/usr/bin/env python3
"""Assemble a standalone Rust submission, checking its array route."""

import argparse
from pathlib import Path
import re
import sys
from compact_rust_source import compact, without_runtime_tests


def without_comments(source):
    """Remove nested Rocq comments, preserving quoted strings."""
    result = []
    depth = 0
    quoted = False
    i = 0
    while i < len(source):
        pair = source[i:i + 2]
        if not quoted and pair == "(*":
            depth += 1
            result.append(" ")
            i += 2
        elif depth and pair == "*)":
            depth -= 1
            i += 2
        elif depth:
            i += 1
        elif pair == '""' and quoted:
            result.append(pair)
            i += 2
        else:
            char = source[i]
            if char == '"':
                quoted = not quoted
            result.append(char)
            i += 1
    if depth or quoted:
        raise ValueError("unterminated comment or string in extraction directives")
    return "".join(result)


def check_route(directives, route):
    source = without_comments(directives)
    imports = set()
    for group in re.findall(
            r"From\s+RustExtraction\s+Require\s+(?:Import|Export)\s+([\w\s]+)\.", source):
        imports.update(group.split())
    cow = bool(re.search(r"\bSet\s+Rust Extraction Copy On Write Arrays\s*\.", source))
    unset = bool(re.search(r"\bUnset\s+Rust Extraction Copy On Write Arrays\s*\.", source))
    expected = {"ArraysStrong"} if route == "strong-cow" else {"Arrays"}
    if imports.intersection({"Arrays", "ArraysStrong"}) != expected or unset:
        raise ValueError(f"extraction directives do not match the {route} array route")
    if not cow:
        raise ValueError(f"copy-on-write option does not match the {route} array route")


def assemble(problem, route, directives, extracted, harness, int63, arrays, license_text,
             extra_runtimes=None, io_helpers=None):
    if not re.fullmatch(r"[a-z][a-z0-9_]*", problem):
        raise ValueError("invalid Kattis problem identifier")
    check_route(directives, route)
    header = (
        f"// Kattis submission for {problem}.\n"
        "// Generated by assemble-submission-rust.py.\n"
        f"// Array route: {route}. Runtime mappings and I/O are trusted.\n"
        + ("// Strong CoW revokes old array versions; it is not persistent-array equivalence.\n"
           if route == "strong-cow" else "")
        + "//\n"
    )
    notice = "".join(f"// {line}\n" if line else "//\n"
                     for line in license_text.splitlines())
    helpers = ""
    if "use kattis_io::*;" in harness:
        if io_helpers is None:
            raise ValueError("missing shared I/O helpers")
        helpers = ("mod kattis_io {\nuse super::STACK_MIB;\n" + io_helpers
                   + "\n}\nuse kattis_io as submission_io;\n")
    extra = ""
    for name in ("rocq_bigint", "rocq_float64", "rocq_string"):
        if re.search(rf"\b{name}\s*::", extracted + "\n" + harness + helpers):
            if not extra_runtimes or name not in extra_runtimes:
                raise ValueError(f"missing required runtime: {name}")
            extra += f"mod {name} {{\n" + without_runtime_tests(extra_runtimes[name]) + "\n}\n\n"
    source = (header + notice + "\n"
            + "mod rocq_int63 {\n" + without_runtime_tests(int63) + "\n}\n\n"
            + "mod rocq_array {\n" + without_runtime_tests(arrays) + "\n}\n\n"
            + extra + extracted + "\n" + helpers + harness)
    # Match the survey's source-size ceiling without changing extracted algorithms.
    if len(source.encode("utf-8")) > 131072:
        source = compact(source)
    if len(source.encode("utf-8")) > 131072:
        raise ValueError(f"{problem}: standalone Rust source exceeds 131072 bytes "
                         f"after trivia compaction ({len(source.encode('utf-8'))} bytes)")
    return source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--problem", required=True)
    parser.add_argument("--array-route", choices=["cow", "strong-cow"], required=True)
    for name in ("directives", "extracted", "harness", "int63", "arrays", "license"):
        parser.add_argument(f"--{name}", type=Path, required=True)
    for name in ("bigint", "float64", "string", "io-helpers"):
        parser.add_argument(f"--{name}", type=Path)
    args = parser.parse_args()
    try:
        output = assemble(args.problem, args.array_route,
                          *(getattr(args, name).read_text() for name in
                            ("directives", "extracted", "harness", "int63", "arrays", "license")),
                          extra_runtimes={f"rocq_{name}": getattr(args, name).read_text()
                                          for name in ("bigint", "float64", "string")
                                          if getattr(args, name) is not None},
                          io_helpers=args.io_helpers.read_text() if args.io_helpers else None)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    sys.stdout.write(output)


if __name__ == "__main__":
    main()
