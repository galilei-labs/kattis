#!/usr/bin/env python3
"""Assemble one deterministic, standalone OCaml submission on stdout."""

import argparse
from pathlib import Path
import re
import sys


def standalone_bigint(path):
    # The shared library source exports its embedded module for separate
    # compilation. Standalone submissions embed that module without exporting
    # its members into the program's top-level namespace (the legacy recipe).
    footer = (
        b'\n\n(* Expose the embedded module as the separately compiled Bigint module,\n'
        b'   matching the legacy arrays_bigint build without changing its arithmetic. *)\n'
        b'include Bigint\n'
    )
    source = path.read_bytes()
    if not source.endswith(footer):
        raise ValueError("shared Bigint source is missing its expected compiled-module export")
    return source[:-len(footer)]


def assemble(problem, shim, extracted, main, route="marray", bigint=None):
    if not re.fullmatch(r"[a-z][a-z0-9_]*", problem):
        raise ValueError("invalid Kattis problem identifier")
    arrays = {"marray": "Marray", "arrays_bigint": "Marray_raw"}[route]
    header = (
        f"(* Kattis submission for {problem}.\n"
        "   Generated by assemble-submission-ocaml.py.\n"
        f"   Route: {route}; arrays = {arrays}.\n"
        "   Extraction/runtime mappings are trusted, not verified. *)\n\n"
    ).encode()
    parts = [header]
    sources = [("standalone runtime", shim.read_bytes())]
    if route == "arrays_bigint":
        if bigint is None:
            raise ValueError("arrays_bigint requires --bigint")
        sources.append(("arbitrary-precision integer runtime", standalone_bigint(bigint)))
    sources.append((f"extracted implementation ({route})", extracted.read_bytes()))
    for title, source in sources:
        parts.extend([f"(* ---- {title} ---- *)\n".encode(),
                       source, b"\n\n"])
    parts.extend([b"(* ---- array interface for the I/O wrapper ---- *)\n",
                  f"module Arr = {arrays}\n\n".encode(),
                  b"(* ---- problem-specific I/O wrapper ---- *)\n",
                  main.read_bytes()])
    return b"".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--problem", required=True)
    parser.add_argument("--route", choices=["marray", "arrays_bigint"], required=True)
    parser.add_argument("--shim", type=Path, required=True)
    parser.add_argument("--extracted", type=Path, required=True)
    parser.add_argument("--main", type=Path, required=True)
    parser.add_argument("--bigint", type=Path)
    args = parser.parse_args()
    try:
        output = assemble(args.problem, args.shim, args.extracted, args.main,
                          route=args.route, bigint=args.bigint)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    sys.stdout.buffer.write(output)


if __name__ == "__main__":
    main()
