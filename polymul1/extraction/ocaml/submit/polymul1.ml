let length_to_int i = Uint63.hash i   (* the identity on 64-bit, allocation-free without flambda; see tools/gen-extract-arrays.py *)

let trunc_size n =
  if Uint63.le Uint63.zero n && Uint63.lt n (Uint63.of_int max_array_length32) then
    length_to_int n
  else max_array_length32

type 'a t = ('a kind) ref
and 'a kind =
  | Array of 'a UArray.t * 'a
  | Updated of int * 'a * 'a t

let unsafe_of_obj t def = ref (Array (UArray.unsafe_of_obj t, def))
let of_array t def = ref (Array (UArray.of_array t, def))

let rec rerootk t k =
  match !t with
  | Array (a, _) -> k a
  | Updated (i, v, p) ->
      let k' a =
        let v' = UArray.unsafe_get a i in
        UArray.unsafe_set a i v;
        t := !p; (* i.e., Array (a, def) *)
        p := Updated (i, v', t);
        k a in
      rerootk p k'

let reroot t = rerootk t (fun a -> a)

let length_int p =
  UArray.length (reroot p)

let length p = Uint63.of_int @@ length_int p

let get p n =
  let t = reroot p in
  let l = UArray.length t in
  if Uint63.le Uint63.zero n && Uint63.lt n (Uint63.of_int l) then
    UArray.unsafe_get t (length_to_int n)
  else
    match !p with
    | Array (_, def) -> def
    | Updated _ -> assert false

let set p n e =
  let a = reroot p in
  let l = Uint63.of_int (UArray.length a) in
  if Uint63.le Uint63.zero n && Uint63.lt n l then
    let i = length_to_int n in
    let v' = UArray.unsafe_get a i in
    UArray.unsafe_set a i e;
    let t = ref !p in (* i.e., Array (a, def) *)
    p := Updated (i, v', t);
    t
  else p

let default p =
  let _ = reroot p in
  match !p with
  | Array (_,def) -> def
  | Updated _ -> assert false

let make_int n def =
  ref (Array (UArray.make n def, def))

let make n def = make_int (trunc_size n) def

let uinit n f =
  if Int.equal n 0 then UArray.empty
  else begin
    let t = UArray.make n (f 0) in
    for i = 1 to n - 1 do
      UArray.unsafe_set t i (f i)
    done;
    t
  end

let init n f def =
  let n = trunc_size n in
  let t = uinit n f in
  ref (Array (t, def))

let to_array p =
  let _ = reroot p in
  match !p with
  | Array (t,def) -> UArray.to_array t, def
  | Updated _ -> assert false

let copy p =
  let _ = reroot p in
  match !p with
  | Array (t, def) -> ref (Array (UArray.copy t, def))
  | Updated _ -> assert false

(* Higher order combinators: the callback may update the underlying
   array requiring a reroot between each call. To avoid doing n
   reroots (-> O(n^2)), we copy if we have to reroot again. *)

let is_rooted p = match !p with
  | Array _ -> true
  | Updated _ -> false

type 'a cache = {
  orig : 'a t;
  mutable self : 'a UArray.t;
  mutable rerooted_again : bool;
}

let make_cache p = {
  orig = p;
  self = reroot p;
  rerooted_again = false;
}

let uget_cache cache i =
  let () = if not cache.rerooted_again && not (is_rooted cache.orig)
    then begin
      cache.self <- UArray.copy (reroot cache.orig);
      cache.rerooted_again <- true
    end
  in
  UArray.unsafe_get cache.self i

let map f p =
  let t = make_cache p in
  let len = UArray.length t.self in
  let res = uinit len (fun i -> f (uget_cache t i)) in
  let def = f (default p) in
  ref (Array (res, def))

let fold_left f x p =
  let r = ref x in
  let t = make_cache p in
  let len = UArray.length t.self in
  for i = 0 to len - 1 do
    r := f !r (uget_cache t i)
  done;
  f !r (default p)

let fold_left2 f a p1 p2 =
  let r = ref a in
  let t1 = make_cache p1 in
  let len = UArray.length t1.self in
  let t2 = make_cache p2 in
  if UArray.length t2.self <> len then invalid_arg "Parray.fold_left2";
  for i = 0 to len - 1 do
    let v1 = uget_cache t1 i in
    let v2 = uget_cache t2 i in
    r := f !r v1 v2
  done;
  f !r (default p1) (default p2)
end

module Marray = struct
(* Marray: OCaml *mutable* arrays behind the interface of Rocq's PrimArray
   primitives, as a drop-in replacement for rocq-runtime's Parray in an
   extra, clearly labelled benchmark column ("marray").

   THIS MAPPING IS UNSOUND IN GENERAL.  Rocq's [PArray.set t i x] is a pure
   function: it returns a new array and [t] keeps its old contents
   ([get_set_other], and [t.[i]] is unchanged).  [Marray.set] writes in
   place and returns the very same array, so any later read of the OLD
   version observes the write.  The two agree exactly when every array is
   used LINEARLY -- each version is consumed once, by the [set] (or the
   final read) that supersedes it, and never read again afterwards.  Every
   spec in this library demands that in its @forbid section, and every
   implementation follows it, but nothing CHECKS it: the column produced
   with this module is an unverified data point ("what would a
   linearity-checking extractor buy?"), never the verified artefact.

   Canonical file: tools/marray.ml at the repository root, which also
   carries [@@inline always] on the primitives (void here: Kattis compiles
   without flambda).  Flavours built from template/ regenerate their
   benchmark/extracted/marray.ml from it at `make extract`.

   Out-of-range behaviour mirrors rocq-runtime/kernel/parray.ml: [get]
   outside the bounds returns the default, [set] outside the bounds is the
   identity, [make] truncates the size to [max_length]. *)

type 'a t = { data : 'a array; def : 'a }

let max_array_length32 = 4194303

let max_length = Uint63.of_int max_array_length32

let length_to_int i = Uint63.hash i   (* the identity on 64-bit, allocation-free without flambda; see tools/gen-extract-arrays.py *)

let trunc_size n =
  if Uint63.le Uint63.zero n && Uint63.lt n (Uint63.of_int max_array_length32)
  then length_to_int n
  else max_array_length32

let make n def = { data = Array.make (trunc_size n) def; def }

let length p = Uint63.of_int (Array.length p.data)

let get p n =
  let l = Array.length p.data in
  if Uint63.le Uint63.zero n && Uint63.lt n (Uint63.of_int l)
  then Array.unsafe_get p.data (length_to_int n)
  else p.def

let set p n e =
  let l = Array.length p.data in
  if Uint63.le Uint63.zero n && Uint63.lt n (Uint63.of_int l)
  then Array.unsafe_set p.data (length_to_int n) e;
  p

let default p = p.def

let copy p = { data = Array.copy p.data; def = p.def }

(* Harness helpers, same names and meaning as Parray's. *)

let of_array a def = { data = Array.copy a; def }

let to_array p = (Array.copy p.data, p.def)
end

