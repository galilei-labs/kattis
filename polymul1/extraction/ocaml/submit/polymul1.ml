   a.(i) / a.(i) <- v pasted at every call site and no array module at all, its arrays are plain ['a array],
   and main.ml only needs the conversions below -- the same names as
   Marray's, on ['a t = 'a array].  Canonical file: tools/marray_raw.ml. *)
