    (* logical shift *)
    (* Branch-free form of the kernel's `if 0 <= y && y < 63 then x lsl y
       else 0` (added for Kattis, 2026-10-30): the mask is -1 when y < 63
       unsigned (the xor flips the sign bit, as in [lt]), else 0, and the
       shift count is reduced mod 64 so the hardware shift is defined. Same
       value for every x, y (fuzzed against the kernel's form, 40M pairs, on
       OCaml 4.14 and 5.4). Why: Kattis's ocamlopt has no flambda and would
       not inline an extracted helper such as `digit s e = land (lsr e s)
       mask` around the branching form, a call per element in
       magicsequence's radix sort (sort phase 1.12 s vs 0.58 s inlined). *)
let l_sl x y =
  (x lsl (y land 63)) land (- (Bool.to_int ((y lxor 0x4000000000000000) < (63 lxor 0x4000000000000000))))
[@@ocaml.inline always]

let l_sr x y =
  (x lsr (y land 63)) land (- (Bool.to_int ((y lxor 0x4000000000000000) < (63 lxor 0x4000000000000000))))
[@@ocaml.inline always]

