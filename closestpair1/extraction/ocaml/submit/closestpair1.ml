[@@ocaml.inline always]

let next_down (x : float) : float = Float.pred x
[@@ocaml.inline always]

let equal f1 f2 =
  if f1 = f2 then f1 <> 0. || sign f1 = sign f2 (* OCaml consider 0. = -0. *)
  else is_nan f1 && is_nan f2
[@@ocaml.inline always]

