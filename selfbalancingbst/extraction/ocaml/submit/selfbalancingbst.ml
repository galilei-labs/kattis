let rec count_loop ops q j acc =
  if bdec (ltb j q)
  then count_loop ops q (add j (Uint63.of_int (1)))
         (if output_command (get ops j)
          then add acc (Uint63.of_int (1))
          else acc)
  else acc

(** val on_cur :
    Uint63.t option -> (Uint63.t -> Uint63.t option) -> Uint63.t option **)

let on_cur cur f =
  match cur with
  | Some c -> f c
  | None -> None

(** val exec :
